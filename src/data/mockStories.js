export async function getStory(id) {
  return mockStories.find((s) => s.id === id) || null
}

// 画面描画時に同期で1件取り出す（体験談詳細ページ用）。
export function getStoryById(id) {
  return mockStories.find((s) => s.id === id) || null
}

export function getStoriesByIds(ids = []) {
  return ids.map((id) => mockStories.find((s) => s.id === id)).filter(Boolean)
}
